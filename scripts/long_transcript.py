def build_transcript(target_tokens, seed=42):
    """Return (text, needles) for a ~target_tokens deterministic Dutch document.

    Five needles are planted at five depths: the 0% needle is the opening ERP
    fact (project PRJ-2247 / budget 487.300); the 25/50/75/100% needles are
    unique synthetic codes injected at the end of each quarter of the filler.
    """
    rng = _random.Random(seed)
    target_chars = int(target_tokens * 4)
    core = "\n".join(SECTIONS)

    depth_needles = []
    for frac_label in ("25%", "50%", "75%", "100%"):
        code = f"RK-{rng.randint(10000, 99999)}-{rng.randint(100, 999)}"
        depth_needles.append({
            "vraag": (f"Wat is de controleaanduiding die bij kwaliteitsregistratie "
                      f"op positie {frac_label} wordt genoemd?"),
            "antwoord_bevat": [code],
            "positie": frac_label,
        })

    needle0 = {
        "vraag": "Wat is de projectreferentie en het toegekende budget van het nieuwe ERP-project?",
        "antwoord_bevat": ["PRJ-2247", "487.300"],
        "positie": "0%",
    }
    needles = [needle0] + depth_needles

    filler = _filler_text(rng, max(0, target_chars - len(core)))
    paras = [p for p in filler.split("\n\n") if p.strip()]
    n = len(paras)
    insert_at = [int(n * 0.25), int(n * 0.5), int(n * 0.75), n]

    out = ["\n" + core + "\n\n"]
    cursor = 0
    for i, needle in enumerate(depth_needles):
        idx = insert_at[i]
        out.append("\n\n".join(paras[cursor:idx]))
        out.append(
            f"\n\n(Notulist — {needle['positie']}-aanduiding.) "
            f"De controleaanduiding voor kwaliteitsregistratie op positie "
            f"{needle['positie']} is {needle['antwoord_bevat'][0]}.\n\n"
        )
        cursor = idx
    out.append("\n\n".join(paras[cursor:]))
    return "".join(out), needles
